# coding: utf-8
"""Нормы трудового права Республики Узбекистан — в одном месте.

Здесь живут величины и сроки, которые задаёт законодательство, а не наш
продукт: МРОТ и сроки регистрации в ЕНСТ. Модуль общий сознательно — расчёт
срока ЕНСТ уже существовал приватно внутри `services/onec/hr.py`, и второй
такой же в кадровом модуле означал бы две половины одного правила, которые
разъедутся при первой же поправке в законе.

Зачем отдельный модуль
----------------------
МРОТ — не константа, а **календарь**: он меняется указом президента, обычно
с 1 сентября. Значение берётся на дату, к которой относится проверяемый факт
(дату вступления редакции штатного расписания в силу), а не «на сегодня» —
иначе редакция, утверждённая задним числом, проверится не тем порогом.

Почему проверка вообще существует
---------------------------------
В Узбекистане требование строже российского. Две нормы ТК РУз вместе:

* **ст. 245** — месячная оплата труда за отработанную месячную норму не может
  быть ниже МРОТ, причём премии, надбавки, стимулирующие и компенсационные
  выплаты, сверхурочные и ночные **в МРОТ не включаются**;
* **ст. 248 ч.2** — **основная (базовая) часть** заработной платы не должна
  быть менее МРОТ.

То есть «добрать» до МРОТ премиями нельзя: сам оклад за полную ставку обязан
быть не ниже МРОТ. В российской модели засчитывается вся зарплата — переносить
её сюда неверно.

При **неполной ставке** порог не применяется: месячная норма не отработана,
оплата пропорциональна отработанному времени (ст. 186, ст. 258 ч.3, ст. 244).
Оклад «за ставку» при этом не уменьшается — уменьшается начисление.

Решение владельца (2026-08-10): нарушение **предупреждает, но не блокирует**.
Закон однозначен, однако ложный отказ останавливает реальную кадровую работу,
а видимое предупреждение своё дело делает.
"""

from __future__ import annotations

import logging
from datetime import date, timedelta
from decimal import Decimal
from typing import Dict, Optional, Tuple

log = logging.getLogger("wage_floor")

# (дата вступления в силу, размер МРОТ в сумах). Отсортирован по возрастанию.
#
# ⚠️ Это НОРМАТИВНЫЕ данные, они устаревают. Обновлять при каждом указе об
# индексации — обычно раз в год, к 1 сентября. Значение до первой записи
# считается неизвестным (см. :func:`_minimum_wage_on`), и проверка молча
# пропускается: врать про порог хуже, чем не проверить.
_SCHEDULE: Tuple[Tuple[date, Decimal], ...] = (
    # Указ УП-91 от 02.06.2025. Дата вступления — 1 сентября по сложившейся
    # практике ежегодной индексации; отдельным актом не сверялась.
    (date(2025, 9, 1), Decimal("1271000")),
    # Указ УП-115 от 23.06.2026 «О повышении размеров заработной платы, пенсий,
    # стипендий и пособий» — повышение на 7%, дата подтверждена.
    (date(2026, 9, 1), Decimal("1360000")),
)

# Полная ставка. Ниже неё порог МРОТ не применяется — оплата пропорциональна.
_FULL_RATE = Decimal("1")


def _minimum_wage_on(day: date) -> Optional[Decimal]:
    """МРОТ, действовавший на указанную дату.

    ``None`` — дата раньше первой известной записи календаря. Это честный
    ответ «не знаю», а не ноль: проверка на неизвестном пороге сказала бы
    пользователю неправду.
    """
    result: Optional[Decimal] = None
    for effective_from, amount in _SCHEDULE:
        if day >= effective_from:
            result = amount
        else:
            break
    if result is None:
        log.debug("minimum wage unknown for %s (before %s)", day, _SCHEDULE[0][0])
    return result


def _is_below_minimum_wage(salary: Decimal, rate: Decimal, day: date) -> bool:
    """Нарушает ли оклад позиции нижнюю границу на эту дату.

    Проверяется **только полная ставка и выше**: при неполной месячная норма
    не отработана и порог не применяется.
    """
    if rate < _FULL_RATE:
        return False
    floor = _minimum_wage_on(day)
    if floor is None:
        return False
    return salary < floor


def describe_violation(salary: Decimal, rate: Decimal, day: date) -> Optional[dict]:
    """Машиночитаемое описание нарушения для интерфейса, либо ``None``.

    Возвращается именно структура, а не готовая фраза: текст живёт в i18n на
    двух языках, а сюда попадают только числа и код.
    """
    if not _is_below_minimum_wage(salary, rate, day):
        return None
    floor = _minimum_wage_on(day)
    return {
        "code": "salary_below_minimum_wage",
        "minimum_wage": str(floor),
        "as_of": day.isoformat(),
    }


# ---------------------------------------------------------------------------
# Сроки регистрации в ЕНСТ (ПКМ №971)
# ---------------------------------------------------------------------------

# Вид кадрового события → срок регистрации в рабочих днях.
ENSST_DEADLINE_WORKING_DAYS: Dict[str, int] = {"hire": 5, "dismissal": 3}

_SATURDAY = 5


def _add_working_days(start: date, days: int) -> date:
    """``start`` + ``days`` рабочих дней. Суббота и воскресенье пропускаются.

    Отсчёт идёт со следующего дня: событие в пятницу + 3 рабочих дня = среда.

    ⚠️ Праздники РУз не учитываются — значит срок получается «не позже»
    реального, и напоминание приходит раньше, а не позже. Ошибаться в эту
    сторону безопасно; в обратную — значит подвести пользователя под штраф.
    """
    if days <= 0:
        return start
    current = start
    added = 0
    while added < days:
        current += timedelta(days=1)
        if current.weekday() < _SATURDAY:
            added += 1
    return current


def ensst_deadline(kind: str, event_date: date) -> Optional[date]:
    """Крайний срок регистрации события в ЕНСТ, либо ``None`` для видов без срока."""
    days = ENSST_DEADLINE_WORKING_DAYS.get(kind)
    if not days:
        return None
    return _add_working_days(event_date, days)


# Публичная поверхность модуля намеренно узкая: снаружи нужны только два
# ответа — «нарушает ли оклад нижнюю границу» и «когда крайний срок ЕНСТ».
# Счёт рабочих дней и календари — внутренности.
__all__ = ["describe_violation", "ensst_deadline"]
